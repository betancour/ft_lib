#include "libft.h"

static void	ft_putnbr_long(long nb, int fd)
{
	if (nb < 0)
	{
		ft_putchar_fd('-', fd);
		nb = -nb;
	}
	if (nb >= 10)
		ft_putnbr_long(nb / 10, fd);
	ft_putchar_fd((char)(nb % 10 + '0'), fd);
}

void	ft_putnbr_fd(int n, int fd)
{
	ft_putnbr_long((long)n, fd);
}
